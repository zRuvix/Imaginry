"use client";

import { motion, useScroll, type MotionValue } from "motion/react";
import { useRef } from "react";
import { CountUp, Marker, useScrollRange } from "./kit";

/** Words of the statement; a number stands for an inline swatch (index into `chips`). */
const STATEMENT: (string | number)[] = [
  ..."Imaginry is a free studio for abstract backgrounds.".split(" "),
  0,
  ..."Stack gradients, glass, light and grain".split(" "),
  1,
  ..."into one-off images and looping video, drawn live by shaders in your browser.".split(" "),
  2,
  ..."Nothing is generated by AI, and nothing you drop in is ever uploaded.".split(" "),
];

const FACTS = [
  { to: 0, prefix: "", suffix: "", label: "AI models involved" },
  { to: 0, prefix: "", suffix: "", label: "photos uploaded, ever" },
  { to: 4, prefix: "", suffix: "K", label: "stills at any ratio" },
  { to: 0, prefix: "$", suffix: "", label: "to make and export" },
];

function Word({ p, range, children }: { p: MotionValue<number>; range: [number, number]; children: string }) {
  const opacity = useScrollRange(p, range, [0.13, 1]);
  return <motion.span style={{ opacity }}>{children} </motion.span>;
}

function Chip({ p, range, url }: { p: MotionValue<number>; range: [number, number]; url: string | null }) {
  const scale = useScrollRange(p, range, [0.3, 1]);
  const rotate = useScrollRange(p, range, [-24, 0]);
  return (
    <motion.span
      aria-hidden
      style={{ scale, rotate }}
      className="mr-[0.22em] inline-block h-[0.78em] w-[1.55em] translate-y-[0.06em] overflow-hidden rounded-full bg-[var(--surface)] align-baseline"
    >
      {url && (
        // eslint-disable-next-line @next/next/no-img-element
        <img src={url} alt="" className="h-full w-full object-cover" />
      )}
    </motion.span>
  );
}

/** One long statement that lights up word by word as it scrolls past. */
export default function Manifesto({ chips }: { chips: (string | null)[] }) {
  const ref = useRef<HTMLParagraphElement>(null);
  const { scrollYProgress: p } = useScroll({ target: ref, offset: ["start 0.85", "end 0.55"] });
  const n = STATEMENT.length;

  return (
    <section className="relative mx-auto max-w-[1400px] px-4 pb-[16vh] pt-[18vh] md:px-8">
      <div className="grid gap-8 md:grid-cols-12">
        <Marker n="01" className="md:col-span-3 md:pt-4">
          What it is
        </Marker>
        <p
          ref={ref}
          className="font-display text-[clamp(26px,3.7vw,58px)] leading-[1.1] tracking-[-0.025em] text-[var(--bone)] md:col-span-9"
        >
          {STATEMENT.map((w, i) => {
            const range: [number, number] = [i / n, Math.min(1, (i + 1.5) / n)];
            return typeof w === "number" ? (
              <Chip key={i} p={p} range={range} url={chips[w] ?? null} />
            ) : (
              <Word key={i} p={p} range={range}>
                {w}
              </Word>
            );
          })}
        </p>
      </div>

      <dl className="mt-[12vh] grid grid-cols-2 border-t border-white/10 md:grid-cols-4">
        {FACTS.map((f, i) => (
          <motion.div
            key={f.label}
            initial={{ opacity: 0, y: 30 }}
            whileInView={{ opacity: 1, y: 0 }}
            viewport={{ once: true, margin: "0px 0px -10% 0px" }}
            transition={{ duration: 1, delay: i * 0.1, ease: [0.16, 1, 0.3, 1] }}
            className={`flex flex-col border-white/10 py-7 md:py-9 ${i % 2 ? "border-l pl-5" : ""} ${
              i > 1 ? "border-t md:border-t-0" : ""
            } ${i > 0 ? "md:border-l md:pl-8" : ""}`}
          >
            <dt className="order-2 mt-3 font-condensed text-[15px] text-[var(--bone)]/55">{f.label}</dt>
            <dd className="font-display text-[clamp(40px,5vw,76px)] leading-none tracking-[-0.04em] text-[var(--bone)]">
              <CountUp to={f.to} prefix={f.prefix} suffix={f.suffix} />
            </dd>
          </motion.div>
        ))}
      </dl>
    </section>
  );
}
